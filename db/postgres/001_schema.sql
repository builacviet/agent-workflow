-- PostgreSQL target schema for the current SQLite workflow, dispatch,
-- webhook inbox and Controller CI ledger. Never run against live SQLite.
-- The migration/cutover adapter is implemented and validated separately.
SET ROLE db_migrator;
SET search_path TO workflow, pg_catalog;

CREATE TABLE IF NOT EXISTS schema_migrations (
  component text NOT NULL,
  version integer NOT NULL,
  name text NOT NULL,
  applied_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY(component, version)
);

CREATE TABLE IF NOT EXISTS tasks (
 task_id text PRIMARY KEY, metadata text NOT NULL, repository text NOT NULL,
 branch text NOT NULL, base_sha text NOT NULL, current_head_sha text,
 requested_effort text NOT NULL, require_verified_effort integer NOT NULL,
 max_review_rounds integer NOT NULL DEFAULT 2 CHECK(max_review_rounds=2),
 completed_review_rounds integer NOT NULL DEFAULT 0 CHECK(completed_review_rounds BETWEEN 0 AND 2),
 status text NOT NULL CHECK(status IN ('AWAITING_HANDOFF','READY_IN_REVIEW','IN_REVIEW','CHANGES_REQUESTED','APPROVED','ESCALATED')),
 created_at double precision NOT NULL, updated_at double precision NOT NULL
);

CREATE TABLE IF NOT EXISTS review_attempts (
 token text PRIMARY KEY, task_id text NOT NULL REFERENCES tasks(task_id),
 expected_sha text NOT NULL, reviewer text NOT NULL, claimed_at double precision NOT NULL,
 expires_at double precision NOT NULL, status text NOT NULL CHECK(status IN ('ACTIVE','EXPIRED','SUBMITTED')),
 submitted_payload text
);
CREATE UNIQUE INDEX IF NOT EXISTS one_active_claim
 ON review_attempts(task_id) WHERE status='ACTIVE';

CREATE TABLE IF NOT EXISTS reviews (
 review_id text PRIMARY KEY, task_id text NOT NULL REFERENCES tasks(task_id),
 round_number integer NOT NULL CHECK(round_number BETWEEN 1 AND 2),
 base_sha text NOT NULL, reviewed_head_sha text NOT NULL, verdict text NOT NULL,
 summary text NOT NULL, requested_effort text NOT NULL, actual_effort text,
 verification_evidence text NOT NULL, reviewer text, reviewed_at double precision,
 imported_at double precision, prior_resolutions text NOT NULL,
 UNIQUE(task_id, round_number), UNIQUE(task_id, reviewed_head_sha)
);

CREATE TABLE IF NOT EXISTS review_findings (
 review_id text NOT NULL REFERENCES reviews(review_id), finding_id text NOT NULL,
 task_id text NOT NULL REFERENCES tasks(task_id), severity text NOT NULL,
 acceptance_criterion text NOT NULL, file_path text NOT NULL, line integer,
 description text NOT NULL, suggested_correction text NOT NULL,
 required_verification text NOT NULL, PRIMARY KEY(task_id, finding_id)
);

CREATE TABLE IF NOT EXISTS task_events (
 event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 task_id text NOT NULL REFERENCES tasks(task_id),
 previous_status text, next_status text NOT NULL, action text NOT NULL,
 sha text, timestamp double precision NOT NULL, metadata text NOT NULL
);

CREATE TABLE IF NOT EXISTS coder_dispatches (
 dispatch_id text PRIMARY KEY, task_id text NOT NULL,
 round_number integer NOT NULL, input_sha text NOT NULL,
 status text NOT NULL CHECK(status IN ('ACTIVE','BLOCKED','DONE','ACKNOWLEDGED')),
 slot integer UNIQUE CHECK(slot=1), deadline double precision NOT NULL,
 result_sha text, detail text NOT NULL DEFAULT '',
 UNIQUE(task_id,round_number,input_sha)
);

CREATE TABLE IF NOT EXISTS coder_runtime_evidence (
 dispatch_id text PRIMARY KEY REFERENCES coder_dispatches(dispatch_id),
 task_id text NOT NULL, input_sha text NOT NULL,
 runtime_name text NOT NULL, declared_runtime_version text NOT NULL,
 observed_image_id text, inference_telemetry text NOT NULL,
 tested_digest text NOT NULL, published_head_sha text NOT NULL,
 recorded_at double precision NOT NULL
);

CREATE TABLE IF NOT EXISTS webhook_inbox (
 delivery_id text PRIMARY KEY NOT NULL,
 event text NOT NULL, action text NOT NULL, repository text NOT NULL,
 installation_id bigint NOT NULL, subject_id bigint NOT NULL,
 head_sha text NOT NULL, body_digest text NOT NULL
);
-- Enforce the current inbox's replay dedup atomically under concurrency.
CREATE UNIQUE INDEX IF NOT EXISTS webhook_inbox_body_digest
 ON webhook_inbox(body_digest);

CREATE TABLE IF NOT EXISTS controller_ci_tasks (
 task_id text PRIMARY KEY REFERENCES tasks(task_id),
 pr_number bigint NOT NULL CHECK(pr_number>0),
 head_sha text NOT NULL, verdict text NOT NULL CHECK(verdict IN ('BLOCKED','FAILURE','SUCCESS')),
 repair_heads integer NOT NULL DEFAULT 0 CHECK(repair_heads BETWEEN 0 AND 2)
);

CREATE TABLE IF NOT EXISTS controller_ci_observations (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 task_id text NOT NULL REFERENCES controller_ci_tasks(task_id),
 pr_number bigint NOT NULL, head_sha text NOT NULL,
 verdict text NOT NULL CHECK(verdict IN ('BLOCKED','FAILURE','SUCCESS')),
 reason text NOT NULL,
 check_run_id bigint, observed_at text NOT NULL,
 workflow_run_id bigint, run_attempt integer
);
CREATE INDEX IF NOT EXISTS controller_ci_observation_lookup
 ON controller_ci_observations(task_id, head_sha, verdict);

CREATE TABLE IF NOT EXISTS controller_ci_processed (
 delivery_id text PRIMARY KEY REFERENCES webhook_inbox(delivery_id),
 processed_at double precision NOT NULL DEFAULT EXTRACT(EPOCH FROM CURRENT_TIMESTAMP)
);

RESET ROLE;
